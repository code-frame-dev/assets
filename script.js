const STORAGE_KEY = "barbarac-lang";

function applyLanguage(lang) {
  const dict = translations[lang] || translations.ru;

  // Plain text nodes
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) {
      el.textContent = dict[key];
    }
  });

  // HTML nodes (allow <br>, <em>)
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (dict[key] !== undefined) {
      el.innerHTML = dict[key];
    }
  });

  // Flavor list items
  document.querySelectorAll("[data-flavor]").forEach((el) => {
    const key = el.getAttribute("data-flavor");
    if (dict.flavors && dict.flavors[key] !== undefined) {
      el.textContent = dict.flavors[key];
    }
  });

  // Update <html lang="">
  document.documentElement.setAttribute("lang", lang === "hy" ? "hy" : lang);

  // Update active state on switcher buttons
  document.querySelectorAll("[data-lang]").forEach((btn) => {
    btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
  });

  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch (e) {
    // ignore storage errors (private mode, etc.)
  }
}

function initLanguageSwitcher() {
  document.querySelectorAll("[data-lang]").forEach((btn) => {
    btn.addEventListener("click", () => {
      applyLanguage(btn.getAttribute("data-lang"));
    });
  });

  let saved = null;
  try {
    saved = localStorage.getItem(STORAGE_KEY);
  } catch (e) {
    // ignore
  }

  const initialLang = saved && translations[saved] ? saved : "ru";
  applyLanguage(initialLang);
}

document.addEventListener("DOMContentLoaded", initLanguageSwitcher);
